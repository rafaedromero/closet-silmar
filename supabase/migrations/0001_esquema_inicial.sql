-- Permisos (Row Level Security)
-- Cualquiera lee lo publicado; solo las administradoras escriben.
-- ─────────────────────────────────────────────────────────────
alter table public.administradoras enable row level security;
alter table public.prendas         enable row level security;
alter table public.prenda_fotos    enable row level security;
alter table public.metodos_pago    enable row level security;
alter table public.zonas_entrega   enable row level security;
alter table public.ajustes         enable row level security;
alter table public.tasas_cambio    enable row level security;
alter table public.eventos         enable row level security;

-- administradoras: cada una ve solo su propia fila (el panel la usa para saber si puede entrar).
-- Se agregan desde el SQL Editor, nunca desde la app.
create policy "ver mi fila" on public.administradoras
  for select to authenticated using (user_id = auth.uid());

-- prendas
create policy "leer prendas publicadas" on public.prendas
  for select to anon, authenticated using (publicada or public.es_admin());
create policy "administrar prendas" on public.prendas
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- prenda_fotos
create policy "leer fotos publicadas" on public.prenda_fotos
  for select to anon, authenticated using (
    public.es_admin() or exists (
      select 1 from public.prendas p where p.id = prenda_id and p.publicada
    )
  );
create policy "administrar fotos" on public.prenda_fotos
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- métodos de pago y zonas
create policy "leer metodos activos" on public.metodos_pago
  for select to anon, authenticated using (activo or public.es_admin());
create policy "administrar metodos" on public.metodos_pago
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

create policy "leer zonas activas" on public.zonas_entrega
  for select to anon, authenticated using (activa or public.es_admin());
create policy "administrar zonas" on public.zonas_entrega
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- ajustes (sin insert ni delete: siempre es una sola fila)
create policy "leer ajustes" on public.ajustes
  for select to anon, authenticated using (true);
create policy "editar ajustes" on public.ajustes
  for update to authenticated using (public.es_admin()) with check (public.es_admin());

-- tasas (la función programada escribe con la clave de servicio, que no pasa por RLS)
create policy "leer tasas" on public.tasas_cambio
  for select to anon, authenticated using (true);
create policy "administrar tasas" on public.tasas_cambio
  for all to authenticated using (public.es_admin()) with check (public.es_admin());

-- eventos: cualquiera registra sobre prendas publicadas; solo las administradoras leen
create policy "registrar evento" on public.eventos
  for insert to anon, authenticated with check (
    exists (select 1 from public.prendas p where p.id = prenda_id and p.publicada)
  );
create policy "leer eventos" on public.eventos
  for select to authenticated using (public.es_admin());

-- Privilegios base (RLS decide fila por fila)
grant select on public.prendas, public.prenda_fotos, public.metodos_pago,
  public.zonas_entrega, public.ajustes, public.tasas_cambio, public.tasa_vigente
  to anon, authenticated;
grant insert on public.eventos to anon, authenticated;
grant select on public.eventos, public.estadisticas_prendas, public.administradoras to authenticated;
grant insert, update, delete on public.prendas, public.prenda_fotos, public.metodos_pago,
  public.zonas_entrega, public.tasas_cambio to authenticated;
grant update on public.ajustes to authenticated;
grant execute on function public.es_admin() to anon, authenticated;

