-- Una sola fila con la configuración de la tienda
create table public.ajustes (
  id                     smallint primary key default 1 check (id = 1),
  whatsapp               text check (whatsapp is null or whatsapp ~ '^[0-9]{10,15}$'), -- solo dígitos, con código de país: 58412...
  titulo                 text not null default 'El Closet de Silmar',
  subtitulo              text not null default 'Ropa que te va a encantar',
  ciudad                 text not null default 'Barquisimeto',
  modo_entrega           public.modo_entrega not null default 'gratis',
  costo_entrega_fijo_usd numeric(10, 2) not null default 0 check (costo_entrega_fijo_usd >= 0),
  tasa_manual            numeric(14, 4) check (tasa_manual is null or tasa_manual > 0),
  usar_tasa_manual       boolean not null default false,
  actualizada_en         timestamptz not null default now()
);

