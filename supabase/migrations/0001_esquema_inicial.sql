-- ─────────────────────────────────────────────────────────────
-- Tasa BCV
-- ─────────────────────────────────────────────────────────────
create table public.tasas_cambio (
  id            bigint generated always as identity primary key,
  tasa          numeric(14, 4) not null check (tasa > 0),
  publicada_en  date not null,                         -- día en que el BCV la publicó
  fuente        public.fuente_tasa not null default 'automatica',
  origen        text,                                  -- servicio consultado, p. ej. "dolarapi"
  registrada_en timestamptz not null default now(),
  unique (publicada_en, fuente)
);

-- La tasa que usa el catálogo: la manual si Silmar la activó; si no, la última automática.
create view public.tasa_vigente
with (security_invoker = on) as
select
  case when a.usar_tasa_manual and a.tasa_manual is not null
       then a.tasa_manual else t.tasa end            as tasa,
  case when a.usar_tasa_manual and a.tasa_manual is not null
       then a.actualizada_en::date else t.publicada_en end as publicada_en,
  case when a.usar_tasa_manual and a.tasa_manual is not null
       then 'manual' else 'automatica' end           as fuente
from public.ajustes a
left join lateral (
  select tasa, publicada_en
  from public.tasas_cambio
  where fuente = 'automatica'
  order by publicada_en desc, registrada_en desc
  limit 1
) t on true
where a.id = 1;

-- ─────────────────────────────────────────────────────────────
-- Estadísticas anónimas
-- ─────────────────────────────────────────────────────────────
create table public.eventos (
  id        bigint generated always as identity primary key,
  prenda_id uuid not null references public.prendas (id) on delete cascade,
  tipo      public.tipo_evento not null,
  sesion    uuid not null,          -- identificador aleatorio generado en el teléfono
  creado_en timestamptz not null default now(),
  unique (prenda_id, tipo, sesion)  -- cada teléfono cuenta una vez por tipo y prenda
);

create index eventos_prenda_idx on public.eventos (prenda_id, tipo);

create view public.estadisticas_prendas
with (security_invoker = on) as
select
  p.id,
  p.ref,
  p.nombre,
  p.vendida_en,
  count(*) filter (where e.tipo = 'vista')    as vistas,
  count(*) filter (where e.tipo = 'me_gusta') as me_gusta,
  count(*) filter (where e.tipo = 'paso')     as pasos,
  count(*) filter (where e.tipo = 'ficha')    as fichas,
  count(*) filter (where e.tipo = 'whatsapp') as whatsapp
from public.prendas p
left join public.eventos e on e.prenda_id = p.id
group by p.id;

